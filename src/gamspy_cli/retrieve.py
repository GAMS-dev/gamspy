from __future__ import annotations

import os
import subprocess

import certifi
import typer

from .util import cli_error

app = typer.Typer(
    short_help="To retrieve a license with another node's information.",
    help="[bold][yellow]Examples[/yellow][/bold]: gamspy retrieve license <access_code> [--input <input_path>.json] [--output <output_path>.json]",
    context_settings={"help_option_names": ["-h", "--help"]},
)


def retrieve_license(
    access_code: str,
    input: str,
    *,
    output: str | None = None,
    checkout_duration: int | None = None,
) -> str:
    """
    Retrieves a license with the information of another node. Equivalent of
    ``gamspy retrieve license``.

    Parameters
    ----------
    access_code : str
        Access code of the license.
    input : str
        Path of the JSON file with the node information generated by :func:`probe`.
    output : str, optional
        Output path for the license file.
    checkout_duration : int, optional
        Duration in hours to checkout a session.

    Returns
    -------
    str
        Content of the license.

    Raises
    ------
    CLIError
        In case the license cannot be retrieved.

    Examples
    --------
    >>> from gamspy import cli
    >>> _ = cli.probe(json_out="node_info.json")  # doctest: +SKIP
    >>> license = cli.retrieve_license("<access_code>", "node_info.json")  # doctest: +SKIP

    """
    import gamspy_base

    if input is None or not os.path.isfile(input):
        raise cli_error(
            f"Given path `{input}` is not a json file. Please use `gamspy retrieve license <access_code> -i <json_file_path>`"
        )

    if access_code is None:
        raise cli_error(f"Given licence id `{access_code}` is not valid!")

    environment_variables = os.environ.copy()
    if "CURL_CA_BUNDLE" not in environment_variables:
        environment_variables["CURL_CA_BUNDLE"] = certifi.where()

    command = [
        os.path.join(gamspy_base.directory, "gamsgetkey"),
        access_code,
        "-i",
        input,
    ]
    if checkout_duration:
        command.append("-c")
        command.append(str(checkout_duration))

    process = subprocess.run(
        command, text=True, capture_output=True, env=environment_variables
    )

    if process.returncode:
        raise cli_error(process.stderr)

    if output:
        with open(output, "w") as file:
            file.write(process.stdout)

    return process.stdout


@app.command(
    short_help="Retrives the license with the given node information.",
    help="[bold][yellow]Examples[/yellow][/bold]: gamspy retrieve license <access_code> [--input <input_path>.json] [--output <output_path>.json]",
)
def license(
    access_code: str = typer.Argument(..., help="Access code of the license."),
    input: str = typer.Option(
        None,
        "--input",
        "-i",
        help="Input json file path to retrieve the license based on the node information.",
    ),
    output: str = typer.Option(
        None, "--output", "-o", help="Output path for the license file."
    ),
    checkout_duration: int | None = typer.Option(
        None,
        "--checkout-duration",
        "-c",
        help="Specifies a duration in hours to checkout a session.",
    ),
) -> None:
    print(
        retrieve_license(
            access_code, input, output=output, checkout_duration=checkout_duration
        )
    )


if __name__ == "__main__":
    app()
