from __future__ import annotations

import os
from typing import TYPE_CHECKING, TextIO, cast

import gamspy._backend.backend as backend
import gamspy._gdx as gdxio
import gamspy._miro as miro
from gamspy._internals import ATTR_PREFIX, DataSource
from gamspy._miro import IS_MIRO_INIT
from gamspy._options import Options
from gamspy.exceptions import GamspyException, ValidationError, _customize_exception

if TYPE_CHECKING:
    from pathlib import Path

    import pandas as pd

    from gamspy import Container, Model


# A grid solver reads its option file only when it starts, so every
# uncollected local asynchronous solve needs an optfile number of its own.
ASYNC_OPTION_FILE_NUMBERS = range(100, 1000)


def acquire_option_file_number(container: Container) -> int:
    in_use = container._async_option_file_numbers
    for number in ASYNC_OPTION_FILE_NUMBERS:
        if number not in in_use:
            in_use.add(number)
            return number

    raise ValidationError(
        f"At most {len(ASYNC_OPTION_FILE_NUMBERS)} local asynchronous solves with"
        " solver options can be in flight at once. Collect some of them with"
        " `SolveHandle.wait` first."
    )


def release_option_file_number(container: Container, number: int) -> None:
    container._async_option_file_numbers.discard(number)


class Local(backend.Backend):
    def __init__(
        self,
        container: Container,
        options: Options,
        solver: str | None,
        solver_options: dict | Path | None,
        output: TextIO | None,
        model: Model | None,
    ) -> None:
        super().__init__(
            "local",
            container,
            options,
            solver,
            solver_options,
            output,
        )
        self.model = model

    def is_async(self) -> bool:
        return self.model is not None and self.options._async_mode == "submit"

    def create_handle(self) -> LocalSolveHandle:
        model = cast("Model", self.model)

        symbol_names = gdxio._get_symbol_names_from_gdx(
            self.container.system_directory, self.container._gdx_out
        )
        self.container._should_load_from(symbol_names, source=DataSource.GAMS)

        return LocalSolveHandle(
            model,
            int(model._handle),
            cast("str", self.solver),
            self.options,
        )

    def run(self) -> pd.DataFrame | None:
        if self.model is not None:
            self.model._assign_model_attributes()

        # Generate gams string
        gams_string = self.preprocess()

        # Run the model
        self.execute_gams(gams_string)

        # Synchronize GAMSPy with checkpoint and return a summary
        summary = self.postprocess()

        return summary

    def execute_gams(self, gams_string: str) -> None:
        try:
            self.container._execution_engine.execute(
                gams_string, self.options, self.job_name, self.model, self.output
            )

            if self.model:
                self.model._update_model_attributes(is_submission=self.is_async())
                self.container._delete_autogenerated_symbols()
        except GamspyException as exception:
            self.container._workspace._errors.append(str(exception))
            message = _customize_exception(
                self.options,
                self.job_name,
                exception.return_code,
            )

            exception.args = (exception.message + message,)
            raise exception
        finally:
            self.container._unsaved_statements = []

    def postprocess(self) -> pd.DataFrame | None:
        miro.load_miro_symbol_records(self.container)

        if self.model is not None:
            self.parse_listings(self.model)

            if self.options._async_mode is not None:
                return None

            return self.prepare_summary(self.model)

        return None


class LocalSolveHandle(backend.SolveHandle):
    """
    Handle of an asynchronous solve by :meth:`Model.solveAsync <gamspy.Model.solveAsync>`.
    This class is not meant to be instantiated directly.
    """

    backend = "local"

    def __init__(
        self,
        model: Model,
        value: int,
        solver: str,
        options: Options,
    ) -> None:
        super().__init__(model)
        self.value = value
        self._solver = solver
        self._option_file_number = options._option_file_number
        self._report_solution = options.report_solution
        self._listing_file = options.listing_file

    @property
    def _job_id(self) -> int:
        return self.value

    @property
    def _grid_gdx_file(self) -> str:
        return self.model._attr_gdx_file[:-4] + "_grid.gdx"

    def _read_handle_status(self) -> int:
        status_name = f"{ATTR_PREFIX}grid_status_{self.model._auto_id}"
        return int(
            gdxio._get_model_attr_records(
                self.model.container, self._grid_gdx_file, [status_name]
            )[status_name]
        )

    def isReady(self) -> bool:
        self._validate()

        container = self.model.container
        status_name = f"{ATTR_PREFIX}grid_status_{self.model._auto_id}"

        container._add_statement("$offListing")
        container._add_statement(f"Scalar {status_name};")
        container._add_statement(f"{status_name} = handleStatus({self.value});")
        container._add_statement(
            f"execute_unload '{self._grid_gdx_file}', {status_name};"
        )
        container._add_statement("$onListing")

        runner = backend.backend_factory(container, Options(), output=container.output)
        runner.run()

        return self._read_handle_status() != 1

    def wait(
        self,
        timeout: float | None = None,
        output: TextIO | None = None,
        options: Options | None = None,
    ) -> pd.DataFrame:
        self._validate_timeout(timeout)
        self._validate()

        model = self.model
        container = model.container

        if output is None:
            output = container.output

        handle = f"{model.name}.handle"
        ret_name = f"{ATTR_PREFIX}grid_ret_{model._auto_id}"
        status_name = f"{ATTR_PREFIX}grid_status_{model._auto_id}"
        error_name = f"{ATTR_PREFIX}grid_error_{model._auto_id}"
        log_file_name = f"{ATTR_PREFIX}grid_log"
        solver_log = os.path.join(
            container._process_directory, f"grid{self.value}", "gmsgrid.log"
        )

        container._add_statement("$offListing")
        container._add_statement(f"Scalar {ret_name};")
        container._add_statement(f"Scalar {status_name};")
        container._add_statement(f"Scalar {error_name};")
        container._add_statement(f"file {log_file_name};")
        container._add_statement(f"{handle} = {self.value};")
        if timeout is None:
            container._add_statement(
                f"repeat {ret_name} = readyCollect({handle}, 3600); until handleStatus({handle}) <> 1;"
            )
        elif timeout > 0:
            # readyCollect blocks until the solution is ready or timeout
            # seconds passed. With timeout=0, only the status is checked
            # without waiting (readyCollect treats 0 as no limit).
            container._add_statement(f"{ret_name} = readyCollect({handle}, {timeout});")

        # handleStatus: 0 unknown, 1 still running, 2 solution ready, 3 done
        # but the solution cannot be retrieved.
        container._add_statement(f"{status_name} = handleStatus({handle});")
        # Copy the solver log into the job log. A missing log is not an error.
        container._add_statement(
            f"if({status_name} >= 2, {error_name} = execError;"
            f" put_utility {log_file_name} 'incLog' / '{solver_log}';"
            f" execError = {error_name};);"
        )
        container._add_statement(
            f"if({status_name} = 2, execute_loadhandle {model.name}; {ret_name} = handleDelete({handle}); {handle} = 0;);"
        )
        container._add_statement(
            f"if({status_name} = 3, {ret_name} = handleDelete({handle}); {handle} = 0;);"
        )
        container._add_statement(
            f"execute_unload '{self._grid_gdx_file}', {status_name};"
        )
        container._add_statement("$onListing")

        if options is None:
            options = Options()
            if self._report_solution == 1:
                options = Options(report_solution=1, listing_file=self._listing_file)
        else:
            options = options.model_copy()
        options._async_mode = "collect"
        runner = backend.backend_factory(
            container,
            options,
            self._solver,
            None,
            output,
            "local",
            None,
            model,
        )

        runner.run()

        handle_status = self._read_handle_status()

        symbol_names = gdxio._get_symbol_names_from_gdx(
            container.system_directory, container._gdx_out
        )
        container._should_load_from(symbol_names, source=DataSource.GAMS)

        if handle_status == 1:
            raise TimeoutError(
                f"The asynchronous solve of model `{model.name}` did not finish within {timeout} seconds."
            )

        self._is_collected = True

        release_option_file_number(container, self._option_file_number)

        if handle_status != 2:
            raise GamspyException(
                f"The solution of the asynchronous solve of model `{model.name}`"
                f" could not be retrieved (handle status: {handle_status}).",
                handle_status,
            )

        if IS_MIRO_INIT:
            miro._write_default_gdx_miro(container)

        return runner.prepare_summary(model)
